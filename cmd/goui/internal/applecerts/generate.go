//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"crypto/x509"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"
)

func main() {
	inputs := []struct{ url, hash string }{
		{"https://www.apple.com/appleca/AppleIncRootCertificate.cer", "b0b1730ecbc7ff4505142c49f1295e6eda6bcaed7e2c68c5be91b5a11001f024"},
		{"https://www.apple.com/certificateauthority/AppleRootCA-G2.cer", "c2b9b042dd57830e7d117dac55ac8ae19407d38e41d88f3215bc3a890444a050"},
		{"https://www.apple.com/certificateauthority/AppleRootCA-G3.cer", "63343abfb89a6a03ebb57e9b3f5fa7be7c4f5c756f3017b3a8c488c3653e9179"},
	}
	var source strings.Builder
	source.WriteString("// Code generated by go generate; DO NOT EDIT.\n// Public roots: https://www.apple.com/certificateauthority/\npackage applecerts\nvar certificates = []string{\n")
	client := &http.Client{Timeout: 30 * time.Second}
	for _, in := range inputs {
		resp, err := client.Get(in.url)
		must(err)
		if resp.StatusCode != http.StatusOK {
			panic(resp.Status)
		}
		b, err := io.ReadAll(io.LimitReader(resp.Body, 4097))
		resp.Body.Close()
		must(err)
		if fmt.Sprintf("%x", sha256.Sum256(b)) != in.hash {
			panic("Apple certificate digest mismatch")
		}
		cert, err := x509.ParseCertificate(b)
		must(err)
		// Trust anchors are pinned by SHA-256 above. Do not require their legacy
		// self-signature algorithm to pass end-entity signature policy.
		if !cert.IsCA || !bytes.Equal(cert.RawIssuer, cert.RawSubject) {
			panic("expected an Apple root CA")
		}
		fmt.Fprintf(&source, "// %s\n// SHA-256: %s\n%s,\n", in.url, in.hash, strconv.Quote(string(b)))
	}
	source.WriteString("}\n")
	b, err := format.Source([]byte(source.String()))
	must(err)
	must(os.WriteFile("data.go", b, 0644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
