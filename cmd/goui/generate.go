package main

import (
	"context"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
)

func generate(ctx context.Context, c *config, t target, tags, output string) ([]string, error) {
	icon, err := loadIcon(c)
	if err != nil {
		return nil, err
	}
	assets, err := resourceFiles(c, t, icon)
	if err != nil {
		return nil, err
	}
	if t.OS == "darwin" && c.MacOS.Sandbox {
		assets["Entitlements.plist"] = macOSEntitlements(c)
	}
	if output == "" {
		output = filepath.Join("dist", t.folder(), "resources")
	}
	output = c.path(output)
	var files []string
	for _, name := range sortedNames(assets) {
		path := filepath.Join(output, filepath.FromSlash(name))
		if err := writeGenerated(path, assets[name]); err != nil {
			return nil, err
		}
		files = append(files, path)
	}
	if file, err := generateMetadata(c); err != nil {
		return nil, err
	} else if file != "" {
		files = append(files, file)
	}
	if t.OS == "windows" {
		pkg, err := mainPackage(ctx, c, t, tags)
		if err != nil {
			return nil, err
		}
		file, err := generateWindows(c, pkg, assets)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}
	return files, nil
}

func sortedNames(files map[string][]byte) []string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func resourceFiles(c *config, t target, icon *appIcon) (map[string][]byte, error) {
	files := map[string][]byte{}
	switch t.OS {
	case "windows":
		data, err := nativeIcon(c, icon, "windows")
		if err != nil {
			return nil, err
		}
		files["AppIcon.ico"] = data
		files["app.manifest"] = []byte(windowsManifest(c))
	case "darwin":
		data, err := nativeIcon(c, icon, "darwin")
		if err != nil {
			return nil, err
		}
		files["Contents/Resources/AppIcon.icns"] = data
		files["Contents/Info.plist"] = plist(c)
	case "linux":
		files["usr/share/applications/"+c.ID+".desktop"] = []byte(desktopEntry(c))
		for _, size := range []int{16, 24, 32, 48, 64, 128, 256, 512} {
			data, err := pngBytes(icon.image(size))
			if err != nil {
				return nil, err
			}
			name := fmt.Sprintf("usr/share/icons/hicolor/%dx%d/apps/%s.png", size, size, c.ID)
			files[name] = data
		}
		if icon.svg != nil {
			files["usr/share/icons/hicolor/scalable/apps/"+c.ID+".svg"] = icon.raw
		}
	default:
		return nil, fmt.Errorf("unsupported resources target %s", t)
	}
	return files, nil
}

func generateMetadata(c *config) (string, error) {
	if c.Metadata == "" {
		return "", nil
	}
	path := c.path(filepath.Join(c.Metadata, "goui_metadata.go"))
	data, err := format.Source([]byte(fmt.Sprintf(`// Code generated by goui; DO NOT EDIT.
package appinfo

const (
    ID = %q
    Name = %q
    Version = %q
    Build = %d
)
`, c.ID, c.Name, c.Version, c.Build)))
	if err != nil {
		return "", err
	}
	// This helper owns one generated file, not the package directory.
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return "", err
	}
	if err := writeGenerated(path, data); err != nil {
		return "", err
	}
	return path, nil
}
