package base

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

const entryFileName = "zz_goui_mobile_main.go"
const entrySource = `// Code generated by goui. DO NOT EDIT.
package main

import gouiMobile "github.com/golang-gui/goui/platform/mobile"

func init() { gouiMobile.RegisterMain(main) }
`

// ValidateEntryOverlay accepts only the generated main registration. The Go
// driver embeds this same source so validation and generation share one template.
func ValidateEntryOverlay(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var overlay struct{ Replace map[string]string }
	if err = json.Unmarshal(data, &overlay); err != nil || len(overlay.Replace) != 1 {
		return "", fmt.Errorf("entry overlay must contain exactly one generated main file")
	}
	for target, source := range overlay.Replace {
		if !filepath.IsAbs(target) || filepath.Base(target) != entryFileName || !filepath.IsAbs(source) {
			return "", fmt.Errorf("invalid entry overlay path")
		}
		if _, err = os.Lstat(target); !os.IsNotExist(err) {
			return "", fmt.Errorf("entry overlay target must not exist: %s", target)
		}
		data, err = os.ReadFile(source)
		if err != nil {
			return "", err
		}
		if string(data) != entrySource {
			return "", fmt.Errorf("entry overlay source differs from built-in registration")
		}
		return filepath.Dir(target), nil
	}
	panic("unreachable")
}
